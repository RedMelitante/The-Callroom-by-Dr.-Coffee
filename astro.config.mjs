// @ts-check
import { defineConfig } from 'astro/config';
import preact from '@astrojs/preact';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';
import cloudflareRedirects from './scripts/cloudflare-redirects.mjs';

export default defineConfig({
  site: process.env.SITE_URL || 'https://callroomcoffee.com',
  trailingSlash: 'never',
  // about-us.html instead of about-us/index.html, so Cloudflare serves /about-us directly
  build: { format: 'file' },
  integrations: [
    preact(),
    sitemap({
      // Leave out private pages and the old-URL redirects
      filter: (page) => !/\/(cart|checkout|account|order\/confirmed|coffee-cart|frequently-asked-questions|shop)$/.test(page),
    }),
    cloudflareRedirects(),
  ],
  vite: {
    plugins: [tailwindcss()],
  },
  // Old WordPress URLs -> new routes (fallback pages for other hosts; on Cloudflare the 301s in
  // dist/_redirects, generated by scripts/cloudflare-redirects.mjs, take precedence)
  redirects: {
    '/coffee-cart': '/coffee-cart-events',
    '/frequently-asked-questions': '/faq',
    '/shop': '/menu',
  },
});
